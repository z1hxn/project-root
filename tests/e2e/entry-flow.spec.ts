import { test, expect } from '@playwright/test';
import { PrismaClient } from '@prisma/client';

const db = new PrismaClient();
const username = `entry_${Date.now().toString(36)}`;
const password = 'Entry-flow-42';

test.afterAll(async () => {
  await db.user.deleteMany({ where: { username } });
  await db.$disconnect();
});

test('public pages and new analyst entry preserve the account session', async ({ page }) => {
  test.setTimeout(90000);
  await page.goto('/');
  await expect(page.getByRole('heading', { name: '흩어진 단서, 하나의 진실.' })).toBeVisible();
  await expect(page.getByText('온라인 추리 게임', { exact: true })).toBeVisible();
  const ctaBackgrounds = await page.locator('.landing-hero-actions a').evaluateAll((links) => links.map((link) => getComputedStyle(link).backgroundColor));
  expect(ctaBackgrounds[0]).not.toBe(ctaBackgrounds[1]);
  await page.screenshot({ path: 'test-results/public-home-desktop.png', fullPage: true, animations: 'disabled' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'test-results/public-home-mobile.png', fullPage: true, animations: 'disabled' });
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390);
  await page.setViewportSize({ width: 1440, height: 1000 });
  const homeHeader = await page.locator('.public-header').boundingBox();
  await page.getByRole('link', { name: '커뮤니티', exact: true }).click();
  await expect(page.getByRole('heading', { name: /함께 이야기할 공간을/ })).toBeVisible();
  await expect(page.getByText('준비 중', { exact: true })).toBeVisible();
  const communityHeader = await page.locator('.public-header').boundingBox();
  expect(communityHeader).toMatchObject({ x: homeHeader!.x, y: homeHeader!.y, width: homeHeader!.width, height: homeHeader!.height });
  await page.screenshot({ path: 'test-results/community-desktop.png', fullPage: true, animations: 'disabled' });
  await page.getByRole('link', { name: '워크스테이션', exact: true }).click();
  await expect(page).toHaveURL(/\/login\?next=%2Fgame/);
  const loginHeader = await page.locator('.public-header').boundingBox();
  expect(loginHeader).toMatchObject({ x: homeHeader!.x, y: homeHeader!.y, width: homeHeader!.width, height: homeHeader!.height });
  await page.getByRole('link', { name: '회원가입', exact: true }).last().click();
  await expect(page).toHaveURL(/\/register\?next=%2Fgame/);
  await page.screenshot({ path: 'test-results/register-desktop.png', fullPage: true, animations: 'disabled' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'test-results/register-mobile.png', fullPage: true, animations: 'disabled' });
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByLabel('사용자명', { exact: true }).fill(username);
  await page.getByLabel('이메일', { exact: true }).fill(`${username}@example.test`);
  await page.getByLabel('비밀번호', { exact: true }).fill(password);
  await page.getByLabel('비밀번호 확인', { exact: true }).fill(password);
  await page.getByRole('button', { name: '계정 만들고 시작하기' }).click();
  await expect(page).toHaveURL(/\/intro/);
  await expect(page.getByRole('main', { name: '신규 조사관 인트로' })).toBeVisible();
  await expect(page.getByRole('heading', { name: /PROJECT ROOT에/ })).toBeVisible();
  await page.screenshot({ path: 'test-results/story-intro-desktop.png', fullPage: true, animations: 'disabled' });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole('button', { name: '다음 장면' })).toBeVisible();
  await page.screenshot({ path: 'test-results/story-intro-mobile.png', fullPage: true, animations: 'disabled' });
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.keyboard.press('ArrowRight');
  await expect(page.getByRole('heading', { name: /우리는 남겨진/ })).toBeVisible();
  await page.getByRole('button', { name: '4번째 장면' }).click();
  await expect(page.getByRole('heading', { name: /한 가지 안내/ })).toBeVisible();
  await page.getByRole('button', { name: '안내 계속 읽기' }).click();
  await expect(page.locator('.story-unknown')).toContainText('왜 당신의 워크스테이션에 남아 있을까요');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'test-results/story-intro-mystery-mobile.png', fullPage: true, animations: 'disabled' });
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole('button', { name: '다음 장면' }).click();
  await expect(page.getByRole('heading', { name: /접속 준비가/ })).toBeVisible();
  await page.getByRole('button', { name: '워크스테이션 연결' }).click();
  await expect(page.getByRole('status')).toBeVisible();
  await expect(page.getByRole('main', { name: '워크스테이션 부팅' })).toBeVisible({ timeout: 12000 });
  await expect(page.getByRole('main', { name: 'OS 로그인' })).toBeVisible({ timeout: 12000 });
  await page.getByRole('button', { name: '워크스테이션 열기' }).click();
  const root = page.getByRole('region', { name: 'Project Root 창', exact: true });
  await expect(root.getByRole('heading', { name: '사라진 링크' })).toBeVisible();
  const user = await db.user.findUniqueOrThrow({ where: { username } });
  expect(user.introCompleted).toBe(true);
  expect(user.briefingCompleted).toBe(true);
  await page.goto('/');
  await expect(page.getByText(username, { exact: true }).first()).toBeVisible();
  await page.goto('/game');
  await expect(page.getByRole('main', { name: 'OS 로그인' })).toBeVisible({ timeout: 12000 });
  await expect(page.getByRole('main', { name: '첫 사건 인트로' })).toHaveCount(0);
});
